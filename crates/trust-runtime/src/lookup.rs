/// Resolves a name in the standard library's global scope (mirrors the
/// interpreter's `Scopes::get`, **by direct reuse**: beyond locals it looks
/// up `library.global`, with a special case for the name `std` on miss; the
/// unknown-variable error on miss carries the minus hint — message and hint
/// are generated by typst itself, zero drift).
pub fn global(engine: &mut Engine, name: &str, span: Span) -> SourceResult<Value> {
    let library: &Library = engine.library;
    let scopes = Scopes::new(Some(library));
    let binding = scopes.get(name).at(span)?;
    Ok(binding.read_checked((engine, span)).clone())
}

/// Creation-time materialization lookup for **code-name captures** (mirrors
/// CapturesVisitor's `Ident → capture(Scopes::get)`): resolves through
/// `Scopes::get`; a miss returns None (at call time the name is resolved by
/// the bindings inside the closure body itself).
pub fn capture_code_opt(engine: &mut Engine, name: &str) -> SourceResult<Option<Value>> {
    let library: &Library = engine.library;
    let scopes = Scopes::new(Some(library));
    Ok(scopes
        .get(name)
        .ok()
        .map(|b| b.read_checked((engine, Span::detached())).clone()))
}

/// Creation-time materialization lookup for **math-name captures** (mirrors
/// CapturesVisitor's `MathIdent → capture(Scopes::get_in_math)`): looks up
/// only the math scope (plus the local chain) — **global-only names are not
/// part of the capture surface** (as in typst issue-2885: `$rgb$` must error
/// with "unknown variable: rgb" rather than resolve to the global function).
pub fn capture_math_opt(engine: &mut Engine, name: &str) -> SourceResult<Option<Value>> {
    let library: &Library = engine.library;
    let scopes = Scopes::new(Some(library));
    Ok(scopes
        .get_in_math(name)
        .ok()
        .map(|b| b.read_checked((engine, Span::detached())).clone()))
}

/// Field access `target.name` (mirrors `access_field`: `Value::field` plus
/// a get-rule style-chain fallback — a field of an element function (e.g.
/// `text.size`) that misses the static field is read from the context's
/// style chain; the sink passes the engine through so deprecation warnings
/// can be emitted).
pub fn field(
    target: &Value,
    name: &str,
    engine: &mut Engine,
    context: Tracked<Context>,
    span: Span,
) -> SourceResult<Value> {
    let err = match target.field(name, (engine, span)).at(span) {
        Ok(value) => return Ok(value),
        Err(err) => err,
    };
    // Check whether this is a get rule field access (mirrors access_field:
    // the styles check is deferred until it is confirmed to be a style-chain
    // field).
    if let Value::Func(func) = target
        && let Some(element) = func.to_element()
        && let Some(id) = element.field_id(name)
    {
        let styles = context.styles();
        let chain = styles.as_ref().map(|&s| s).unwrap_or_default();
        if let Ok(value) = element.field_from_styles(id, chain) {
            let _ = styles.at(span)?;
            return Ok(value);
        }
    }
    Err(err)
}

/// Empty scope (the initial value for generated code's
/// NativeFuncData::scope).
pub fn empty_scope() -> Scope {
    Scope::new()
}

/// Any-return-type description (the initial value for generated code's
/// NativeFuncData::returns).
pub fn any_cast_info() -> typst::foundations::CastInfo {
    typst::foundations::CastInfo::Any
}

/// Runtime wildcard layer for in-body `import <runtime value>: *` (mirrors
/// typst-eval's import.rs: a Func source without a scope reports "cannot
/// import from user-defined functions"; a Module/Type has its scope bound
/// name by name into the current scope, later-wins; other types get the
/// same error). Only wildcard imports whose static chain does not resolve
/// take this path; statically reachable ones stay fully static.
pub fn wild_import(value: &Value, at: Span) -> SourceResult<typst::foundations::Scope> {
    use typst::foundations::Scope;
    let source = match value {
        Value::Module(module) => module.scope(),
        Value::Type(ty) => ty.scope(),
        Value::Func(func) => func.scope().ok_or_else(|| {
            eco_vec![SourceDiagnostic::error(
                at,
                "cannot import from user-defined functions"
            )]
        })?,
        v => {
            return Err(eco_vec![SourceDiagnostic::error(
                at,
                eco_format!("expected path, module, function, or type, found {}", v.ty()),
            )]);
        }
    };
    let mut layer = Scope::new();
    for (name, binding) in source.iter() {
        layer.bind(name.clone(), binding.clone());
    }
    Ok(layer)
}

fn wild_lookup(layers: &[&typst::foundations::Scope], name: &str) -> Option<Value> {
    layers
        .iter()
        .rev()
        .find_map(|scope| scope.get(name).map(|b| b.read().clone()))
}

/// Wildcard-layer lookup + static-chain fallback (when the name also has a
/// static binding: a layer hit wins, mirroring typst's scope chain —
/// wildcard names are bound into the inner scope and shadow the outer
/// ones).
pub fn wild_or(
    layers: &[&typst::foundations::Scope],
    name: &str,
    fallback: Value,
    _at: Span,
) -> SourceResult<Value> {
    Ok(wild_lookup(layers, name).unwrap_or(fallback))
}

/// Wildcard-layer lookup + global fallback (when the name has no static
/// binding).
pub fn wild_or_global(
    layers: &[&typst::foundations::Scope],
    name: &str,
    engine: &mut Engine,
    at: Span,
) -> SourceResult<Value> {
    wild_lookup(layers, name)
        .map(Ok)
        .unwrap_or_else(|| global(engine, name, at))
}
