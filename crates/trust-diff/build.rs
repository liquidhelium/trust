//! Build script for the differential tests: translates fixtures/*.typ to
//! Rust and writes the result into OUT_DIR.
//!
//! Fixtures describe language features only (unrelated to any target
//! package); each fixture exports a group of `#let` bindings, and the test
//! side runs the same calls on both the interpreter and the generated code.

use std::collections::BTreeMap;
use std::path::PathBuf;

fn main() {
    let fixtures = PathBuf::from("fixtures");
    println!("cargo:rerun-if-changed={}", fixtures.display());

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR set"));
    let gen_dir = out_dir.join("gen");
    std::fs::create_dir_all(&gen_dir).expect("create gen dir");

    let mut names = Vec::new();
    // Single-file fixtures: fixtures/*.typ.
    for entry in std::fs::read_dir(&fixtures).expect("read fixtures dir") {
        let entry = entry.expect("entry");
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("typ") {
            continue;
        }
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("stem")
            .to_string();
        let src = std::fs::read_to_string(&path).expect("read fixture");
        let code = trust::translate(&src, &name).unwrap_or_else(|diags| {
            panic!(
                "fixture {name} failed to translate:\n{}",
                diags
                    .iter()
                    .map(|d| format!("  {:?}: {}", d.span, d.message))
                    .collect::<Vec<_>>()
                    .join("\n")
            )
        });
        std::fs::write(gen_dir.join(format!("{name}.rs")), code).expect("write generated");
        names.push(name);
    }
    // Directory fixtures (multi-file packages): fixtures/pkg_*/, with a
    // fixed entry.typ entry point.
    for entry in std::fs::read_dir(&fixtures).expect("read fixtures dir") {
        let entry = entry.expect("entry");
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        let name = path
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("stem")
            .to_string();
        let mut files = BTreeMap::new();
        collect_typ_files(&path, "", &mut files);
        let input = trust::PackageInput {
            files,
            entry: "entry.typ".into(),
            dep_entries: Default::default(),
        };
        let code = trust::translate_package(&input, &name).unwrap_or_else(|diags| {
            panic!(
                "package fixture {name} failed to translate:\n{}",
                diags
                    .iter()
                    .map(|d| format!("  {:?}: {}", d.span, d.message))
                    .collect::<Vec<_>>()
                    .join("\n")
            )
        });
        std::fs::write(gen_dir.join(format!("{name}.rs")), code).expect("write generated");
        names.push(name);
    }
    names.sort();

    let mut mod_rs = String::from("// Generated by build.rs\n");
    for name in &names {
        mod_rs.push_str(&format!(
            "#[allow(clippy::all, unused, unused_mut, non_snake_case, non_upper_case_globals, non_camel_case_types, dead_code)]\npub mod {name} {{\n    include!(concat!(env!(\"OUT_DIR\"), \"/gen/{name}.rs\"));\n}}\n\n"
        ));
    }
    std::fs::write(gen_dir.join("mod.rs"), mod_rs).expect("write mod.rs");
}

/// Recursively collects the .typ files under a directory, keyed by POSIX
/// path relative to the package root.
fn collect_typ_files(dir: &PathBuf, prefix: &str, out: &mut BTreeMap<String, String>) {
    for entry in std::fs::read_dir(dir).expect("read dir") {
        let entry = entry.expect("entry");
        let path = entry.path();
        let file_name = entry.file_name();
        let file_name = file_name.to_string_lossy();
        if path.is_dir() {
            collect_typ_files(&path, &format!("{prefix}{file_name}/"), out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("typ") {
            let rel = format!("{prefix}{file_name}");
            let src = std::fs::read_to_string(&path).expect("read file");
            out.insert(rel, src);
        }
    }
}
