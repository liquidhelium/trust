#!/usr/bin/env bash
# Benchmark: a translated standalone program (`trust translate`) versus the
# typst CLI on the same document.
#
#   ./bench.sh [doc.typ] [N]
#
# Without a doc, a deterministic cetz stress workload is generated
# (BENCH_K canvases × BENCH_M elements, default 20 × 60). N is the number
# of timed runs (default 10).
#
# Prerequisites (nothing is auto-installed):
#   - typst 0.15.x on PATH (or TYPST_BIN pointing at it); other versions
#     fail the version gate
#   - cetz in the local package cache (TYPST_PACKAGE_CACHE_PATH or
#     ~/.cache/typst/packages) when generating the workload
# The trust binary is built automatically (it is this repository's own
# artifact); the translated program is built with cargo via --compile.
set -euo pipefail

REPO="$(cd "$(dirname "$0")" && pwd)"
BENCH="${BENCH_DIR:-/tmp/trust-bench}"
N="${2:-10}"
K="${BENCH_K:-20}"
M="${BENCH_M:-60}"

die() { echo "bench: $*" >&2; exit 1; }

mkdir -p "$BENCH"

# ── 1. Workload ─────────────────────────────────────────────────────────
DOC="${1:-}"
if [[ -z "$DOC" ]]; then
  CACHE="${TYPST_PACKAGE_CACHE_PATH:-$HOME/.cache/typst/packages}"
  CETZ_VER="$(ls "$CACHE/preview/cetz" 2>/dev/null | sort -V | tail -1 || true)"
  [[ -n "$CETZ_VER" ]] ||
    die "no cetz in package cache ($CACHE); compile any @preview/cetz doc once, or pass a doc.typ"
  DOC="$BENCH/stress.typ"
  cat > "$DOC" <<EOF
// Generated by bench.sh — cetz stress workload ($K canvases × $M elements).
#set page(width: 400pt, margin: 10pt)
#import "@preview/cetz:$CETZ_VER": canvas, draw

#let cols = (teal, red, orange, blue, green, purple, navy, maroon)
#for c in range($K) [
  #canvas(length: 4pt, {
    for i in range($M) {
      let x = i * 1.0 / $M
      draw.line((0, 0), (x, 1), stroke: 0.5pt + cols.at(calc.rem(c, 8)))
      draw.circle((x, calc.sin(x * 6.283)), radius: 0.03, fill: teal)
    }
    draw.rect((0, 0), (1, 1))
  })
]
EOF
fi
DOC="$(cd "$(dirname "$DOC")" && pwd)/$(basename "$DOC")"
STEM="$(basename "$DOC" .typ)"
echo "workload: $DOC"

# ── 2. typst baseline (version-gated, never auto-installed) ────────────
TYPST="${TYPST_BIN:-$(command -v typst || true)}"
[[ -n "$TYPST" ]] || die "typst not on PATH; install typst 0.15.x or set TYPST_BIN"
V="$("$TYPST" -V 2>/dev/null || true)"
[[ "$V" == *"0.15."* ]] || die "version gate: $TYPST is '${V:-unknown}', need 0.15.x"
echo "golden:   $TYPST ($V)"

# ── 3. Build trust and the translated program ───────────────────────────
( cd "$REPO" && cargo build -p trust ) >&2
TRUST="$REPO/target/debug/trust"
cd "$BENCH"
"$TRUST" translate "$DOC" prog --with-deps --compile >&2
BIN="prog/target/release/$STEM"
[[ -x "$BIN" ]] || die "generated program binary missing"
echo "native:   $BIN"

# ── 4. Correctness gate: benchmark only equivalent output ───────────────
# Compared as SVG: rendered geometry must be byte-identical. (PDF bytes
# are not comparable across independently built binaries — the deflate
# backend may differ, producing different compressed streams for
# identical content; decompressed streams were verified equal.)
mkdir -p gate-a gate-b
find gate-a gate-b -name '*.svg' -delete # stale pages from earlier runs would fake a count diff
SOURCE_DATE_EPOCH=1000000 "$BIN" --format svg gate-a >/dev/null
SOURCE_DATE_EPOCH=1000000 "$TYPST" compile "$DOC" "gate-b/$STEM-{p}.svg" --ignore-system-fonts
mapfile -t A < <(ls "gate-a"/*.svg | sort)
mapfile -t B < <(ls "gate-b"/*.svg | sort)
[[ ${#A[@]} -eq ${#B[@]} && ${#A[@]} -gt 0 ]] ||
  die "page count differs (native ${#A[@]}, golden ${#B[@]})"
for i in "${!A[@]}"; do
  cmp "${A[$i]}" "${B[$i]}" ||
    die "page $((i + 1)) differs — refusing to benchmark a correctness divergence"
done
echo "gate:     ${#A[@]} page(s) byte-identical ✓"

# ── 5. Timing ───────────────────────────────────────────────────────────
timeit() { # microseconds
  local t0 t1
  t0=$(date +%s%N); "$@" >/dev/null 2>&1; t1=$(date +%s%N)
  echo $(((t1 - t0) / 1000))
}
median() { sort -n | awk '{a[NR]=$1} END{print (NR%2 ? a[(NR+1)/2] : (a[NR/2]+a[NR/2+1])/2)}'; }

run_side() {
  local times=()
  for _ in 1 2; do "$@" >/dev/null 2>&1; done # warmup
  for _ in $(seq "$N"); do times+=("$(timeit "$@")"); done
  printf '%s\n' "${times[@]}" | median
}

mkdir -p out-a out-b
if command -v hyperfine >/dev/null 2>&1; then
  hyperfine -w 2 -n "$N" --style basic \
    "$BIN out-a" \
    "$TYPST compile $DOC out-b/$STEM.pdf --ignore-system-fonts" \
    | tee "$BENCH/hyperfine.txt"
fi
A_US=$(run_side "$BIN" out-a)
B_US=$(run_side "$TYPST" compile "$DOC" "out-b/$STEM.pdf" --ignore-system-fonts)

fmt() { awk -v us="$1" 'BEGIN{printf "%.0f ms", us/1000}'; }
echo
echo "────────────────────────────────────────"
printf "native program   %s\n" "$(fmt "$A_US")"
printf "typst CLI        %s\n" "$(fmt "$B_US")"
awk -v a="$A_US" -v b="$B_US" 'BEGIN{printf "speedup          %.1fx\n", b/a}'
echo "────────────────────────────────────────"
