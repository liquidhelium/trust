/// Path segments of mutable places (assignment / mutable-method targets),
/// mirroring typst-eval's `access.rs`: field access and accessor methods
/// (`first`/`last`/`at`).
///
/// typst semantics (`call_method_access` / `access_dict`):
/// - a field segment requires the current value to be a dictionary
///   (`Dict::at_mut`; a missing key errors with a hint);
/// - an `at` segment takes an integer index on arrays, a string key on
///   dictionaries;
/// - `first`/`last` are array-only.
pub enum PlaceSeg {
    /// Dictionary field name (the escaped literal from generation time).
    Field(String),
    /// The index/key for `at` (a `Value` evaluated by generated code).
    At(Value),
    First,
    Last,
}

// --- Lvalue access gate (mirrors typst-eval/src/access.rs and
// Scopes::get_mut) ---
//
// typst concentrates mutability checks in two places: `Binding::write` is
// the sole write gate (the Captured variant reports the read-only error
// according to the capturer), and `Scopes::get_mut`'s miss branch decides
// between a "constant" and an "unknown variable" error based on whether the
// name hits the globals. We reuse typst's pub types directly to trigger the
// same error construction — zero message drift.

/// Assignment / mutable method landing on a **captured binding**: mirrors
/// `Binding::write`'s rejection of `BindingKind::Captured` — construct a
/// Captured binding and call its `write`; the error message (including the
/// function/context expression wording variants) is generated by typst
/// itself.
pub fn bail_captured(capturer: Capturer) -> SourceResult<Value> {
    let err = Binding::detached(Value::None)
        .capture(capturer)
        .write()
        .unwrap_err();
    Err(eco_vec![SourceDiagnostic::error(Span::detached(), err)])
}

/// Assignment target is a **non-lvalue expression**: evaluate side effects
/// first, then error; mirrors the fallback arm of `Access for ast::Expr`
/// (`access.rs:21-24`).
pub fn bail_temporary(span: Span) -> SourceResult<Value> {
    bail!(span, "cannot mutate a temporary value")
}

/// Identifier assignment target missing from every lexical scope: mirrors
/// `Scopes::get_mut`'s miss branch — build `Scopes` with an empty local
/// scope + the global library and call its `get_mut` directly; hitting the
/// globals yields "cannot mutate a constant: {name}" (the `std` special
/// case included), otherwise "unknown variable: {name}" (minus hint
/// included).
pub fn check_mut_unknown(engine: &mut Engine, name: &str, span: Span) -> SourceResult<()> {
    let library: &Library = engine.library;
    Scopes::new(Some(library))
        .get_mut(name)
        .map(|_| ())
        .at(span)?;
    Ok(())
}

/// Evaluation of plain assignments `a.b..k = v` (mirrors
/// `apply_assignment`'s FieldAccess special case: after `access_dict` walks
/// to the **last segment** it inserts directly into the dictionary — a
/// missing key is created, a single hashed write; intermediate segments
/// behave as in [`place_mut`], with at_mut errors). A non-field last
/// segment (at/first/last) takes a mutable reference with [`place_mut`]
/// semantics and writes through it.
pub fn assign_value(
    root: &mut Value,
    path: &[PlaceSeg],
    value: Value,
    span: Span,
) -> SourceResult<()> {
    let Some((last, init)) = path.split_last() else {
        *root = value;
        return Ok(());
    };
    if let PlaceSeg::Field(name) = last {
        let parent = place_mut(root, init, span)?;
        if let Value::Dict(dict) = parent {
            dict.insert(Str::from(name.as_str()), value);
            return Ok(());
        }
    }
    // Non-dictionary-field last segment: the general mutable place
    // (at/first/last or a non-dictionary host).
    *place_mut(root, path, span)? = value;
    Ok(())
}

/// Walks the path segments to a mutable reference (mirrors `Expr::access`;
/// field-segment error messages mirror `access_dict`'s three-way branch).
pub fn place_mut<'a>(
    root: &'a mut Value,
    path: &[PlaceSeg],
    span: Span,
) -> SourceResult<&'a mut Value> {
    let mut current = root;
    for seg in path {
        current = match seg {
            PlaceSeg::Field(name) => match current {
                Value::Dict(dict) => dict.at_mut(name).at(span)?,
                value => access_dict_error(value, span)?,
            },
            PlaceSeg::At(key) => match current {
                Value::Array(array) => {
                    let index: i64 = key.clone().cast().at(span)?;
                    array.at_mut(index).at(span)?
                }
                Value::Dict(dict) => {
                    let key: typst::foundations::Str = key.clone().cast().at(span)?;
                    dict.at_mut(&key).at(span)?
                }
                value => {
                    let ty = value.ty();
                    if ty.scope().get("at").is_some() {
                        bail!(span, "cannot mutate a temporary value")
                    }
                    bail!(span, "type {ty} has no method `at`")
                }
            },
            PlaceSeg::First => match current {
                Value::Array(array) => array.first_mut().at(span)?,
                value => {
                    let ty = value.ty();
                    if ty.scope().get("first").is_some() {
                        bail!(span, "cannot mutate a temporary value")
                    }
                    bail!(span, "type {ty} has no method `first`")
                }
            },
            PlaceSeg::Last => match current {
                Value::Array(array) => array.last_mut().at(span)?,
                value => {
                    let ty = value.ty();
                    if ty.scope().get("last").is_some() {
                        bail!(span, "cannot mutate a temporary value")
                    }
                    bail!(span, "type {ty} has no method `last`")
                }
            },
        };
    }
    Ok(current)
}

/// Non-dictionary branch of mutable field access (mirrors `access_dict`'s
/// three-way split: dedicated getter types / types without fields / static
/// fields not open for mutation).
fn access_dict_error(value: &mut Value, span: Span) -> SourceResult<&mut Value> {
    let ty = value.ty();
    if matches!(
        value,
        Value::Symbol(_) | Value::Content(_) | Value::Module(_) | Value::Func(_) | Value::Args(_)
    ) {
        bail!(span, "cannot mutate fields on {ty}");
    }
    if typst::foundations::fields_on(ty).is_empty() {
        bail!(span, "{ty} does not have accessible fields");
    }
    Err(eco_format!("fields on {ty} are not yet mutable"))
        .hint(eco_format!(
            "try creating a new {ty} with the updated field value instead"
        ))
        .at(span)
}
